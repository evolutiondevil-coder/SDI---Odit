def write(pack_id, title, data, sources, makes=None, verified=True, version=1):
    pack = {"id": pack_id, "version": version, "schema": 1, "title": title, "sources": sources, "verified": verified}
    if makes:
        pack["makes"] = makes
    pack["data"] = {"codes": dict(sorted(data.items()))}
    with open(f"packs/{pack_id}.json", "w", encoding="utf-8") as f:
        json.dump(pack, f, ensure_ascii=False, indent=1)
    print(pack_id, len(data))

