    private fun generic(code: String): String {
        if (code.length < 5) return "Непознат код"
        val letter = code[0]
        val d1 = code[1]
        val system = when (letter) {
            'P' -> "Двигател / скоростна кутия"
            'C' -> "Ходова част (ABS, ESP, окачване, волан)"
            'B' -> "Купе (въздушни възглавници, климатик, светлини, електрика)"
            'U' -> "Комуникация между модулите (CAN шина)"
            else -> "Неизвестна система"
        }
        val manufacturer = when (letter) {
            'P' -> d1 == '1' || (d1 == '3' && code[2] in "0123")
            'U' -> d1 == '1' || d1 == '2'
            else -> d1 == '1' || d1 == '2'
        }
        val sub = if (letter == 'P') {
            when (code[2]) {
                '0', '1', '2' -> ": дозиране на горивото и въздуха"
                '3' -> ": запалване / прекъсвания"
                '4' -> ": контрол на емисиите"
                '5' -> ": обороти, празен ход, спомагателни входове"
                '6' -> ": компютър и изходни вериги"
                '7', '8', '9' -> ": скоростна кутия"
                'A', 'B', 'C' -> ": хибридна / електрическа задвижваща система"
                else -> ""
            }
        } else {
            ""
        }
        return if (manufacturer) {
            "Код на производителя — $system$sub. Описанието зависи от марката."
        } else {
            "Стандартен код — $system$sub."
        }
    }

